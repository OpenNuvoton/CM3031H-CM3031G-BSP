#!/usr/bin/env python3
"""Convert an RGBA logo to a compact RGB565 C include for CM3034/emWin."""

from pathlib import Path
import argparse
from PIL import Image


def rgb565(red: int, green: int, blue: int) -> int:
    return ((red & 0xF8) << 8) | ((green & 0xFC) << 3) | (blue >> 3)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    image = Image.open(args.input).convert("RGBA")
    if image.size != (320, 98):
        raise SystemExit(f"expected 320x98 logo, got {image.size[0]}x{image.size[1]}")

    pixels = []
    source = image.load()
    for y in range(image.height):
        for x in range(image.width):
            red, green, blue, alpha = source[x, y]
            # Composite antialiased logo edges onto the LCD's black background.
            red = (red * alpha + 127) // 255
            green = (green * alpha + 127) // 255
            blue = (blue * alpha + 127) // 255
            pixels.append(rgb565(red, green, blue))

    lines = [
        "/* Generated by logo2rgb565.py. Do not edit manually. */",
        "#define NUVOTON_LOGO_WIDTH  320",
        "#define NUVOTON_LOGO_HEIGHT 98",
        "static const uint16_t _NuvotonLogoRGB565[NUVOTON_LOGO_WIDTH * NUVOTON_LOGO_HEIGHT] = {",
    ]
    for offset in range(0, len(pixels), 12):
        chunk = pixels[offset:offset + 12]
        lines.append("  " + ",".join(f"0x{value:04X}u" for value in chunk) + ",")
    lines.extend(["};", ""])
    args.output.write_text("\n".join(lines), encoding="ascii")
    print(f"generated {args.output}: {image.size[0]}x{image.size[1]}, {len(pixels) * 2} bytes")


if __name__ == "__main__":
    main()
