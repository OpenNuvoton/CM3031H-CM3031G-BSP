from pathlib import Path
from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Assets" / "Pet_Source.png"
PREVIEW = ROOT / "Assets" / "Pet_64x64.png"
OUTPUT = ROOT / "Application" / "Pet_Sprite_64x64.inc"
SIZE = 64


def main():
    source = Image.open(SOURCE).convert("RGBA")
    alpha = source.getchannel("A")
    bbox = alpha.getbbox()
    if bbox is None:
        raise RuntimeError("source image is fully transparent")

    source = source.crop(bbox)
    source.thumbnail((SIZE - 4, SIZE - 4), Image.Resampling.LANCZOS)
    sprite = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    x = (SIZE - source.width) // 2
    y = (SIZE - source.height) // 2
    sprite.alpha_composite(source, (x, y))
    sprite.save(PREVIEW)

    # emWin palette entry zero is transparent.  Quantize the remaining image
    # to at most 255 opaque colors and shift every visible index by one.
    rgb = Image.new("RGB", sprite.size, (255, 255, 255))
    rgb.paste(sprite.convert("RGB"), mask=sprite.getchannel("A"))
    indexed = rgb.quantize(colors=255, method=Image.Quantize.MEDIANCUT)
    raw_palette = indexed.getpalette()[: 255 * 3]
    raw_palette += [0] * (255 * 3 - len(raw_palette))

    colors = [0]
    for i in range(255):
        r, g, b = raw_palette[i * 3 : i * 3 + 3]
        colors.append((b << 16) | (g << 8) | r)  # GUI_COLOR is 0x00BBGGRR.

    alpha_data = list(sprite.getchannel("A").getdata())
    index_data = list(indexed.getdata())
    pixels = [0 if a < 96 else idx + 1 for idx, a in zip(index_data, alpha_data)]

    lines = [
        "/* Generated by Tools/ConvertPetSprite.py. */",
        "#define PET_SPRITE_WIDTH  64",
        "#define PET_SPRITE_HEIGHT 64",
        "",
        "static const GUI_COLOR _PetColors[256] = {",
    ]
    for offset in range(0, len(colors), 8):
        values = ", ".join(f"0x{value:08X}u" for value in colors[offset : offset + 8])
        lines.append(f"  {values},")
    lines += [
        "};",
        "",
        "static const GUI_LOGPALETTE _PetPalette = {",
        "  256, 1, _PetColors",
        "};",
        "",
        "static const unsigned char _PetPixels[PET_SPRITE_WIDTH * PET_SPRITE_HEIGHT] = {",
    ]
    for offset in range(0, len(pixels), 16):
        values = ", ".join(f"0x{value:02X}" for value in pixels[offset : offset + 16])
        lines.append(f"  {values},")
    lines += [
        "};",
        "",
        "static const GUI_BITMAP _PetBitmap = {",
        "  PET_SPRITE_WIDTH, PET_SPRITE_HEIGHT, PET_SPRITE_WIDTH, 8,",
        "  _PetPixels, &_PetPalette, NULL",
        "};",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="ascii")
    print(f"Wrote {PREVIEW}")
    print(f"Wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
