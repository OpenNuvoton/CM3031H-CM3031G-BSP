from pathlib import Path
from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Assets" / "Pet_Walk_Source_v2.png"
PREVIEW = ROOT / "Assets" / "Pet_Walk_3x64_v2.png"
OUTPUT = ROOT / "Application" / "Pet_Walk_3x64.inc"
SIZE = 64
FRAME_COUNT = 3


def fit_frame(frame: Image.Image) -> Image.Image:
    alpha = frame.getchannel("A")
    bbox = alpha.point(lambda value: 255 if value >= 32 else 0).getbbox()
    if bbox is None:
        raise RuntimeError("walk frame is fully transparent")
    frame = frame.crop(bbox)
    frame.thumbnail((SIZE - 2, SIZE - 2), Image.Resampling.LANCZOS)
    result = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    result.alpha_composite(frame, ((SIZE - frame.width) // 2, SIZE - frame.height - 1))
    return result


def main():
    source = Image.open(SOURCE).convert("RGBA")
    frames = []
    for index in range(FRAME_COUNT):
        x0 = index * source.width // FRAME_COUNT
        x1 = (index + 1) * source.width // FRAME_COUNT
        frames.append(fit_frame(source.crop((x0, 0, x1, source.height))))

    preview = Image.new("RGBA", (SIZE * FRAME_COUNT, SIZE), (0, 0, 0, 0))
    for index, frame in enumerate(frames):
        preview.alpha_composite(frame, (index * SIZE, 0))
    preview.save(PREVIEW)

    rgb = Image.new("RGB", preview.size, (255, 255, 255))
    rgb.paste(preview.convert("RGB"), mask=preview.getchannel("A"))
    indexed = rgb.quantize(colors=255, method=Image.Quantize.MEDIANCUT)
    raw_palette = indexed.getpalette()[: 255 * 3]
    raw_palette += [0] * (255 * 3 - len(raw_palette))

    colors = [0]
    for index in range(255):
        red, green, blue = raw_palette[index * 3:index * 3 + 3]
        colors.append((blue << 16) | (green << 8) | red)

    alpha_data = list(preview.getchannel("A").getdata())
    index_data = list(indexed.getdata())
    atlas_pixels = [0 if alpha < 80 else value + 1
                    for value, alpha in zip(index_data, alpha_data)]
    frames_pixels = []
    atlas_width = SIZE * FRAME_COUNT
    for frame_index in range(FRAME_COUNT):
        values = []
        for y in range(SIZE):
            start = y * atlas_width + frame_index * SIZE
            values.extend(atlas_pixels[start:start + SIZE])
        frames_pixels.append(values)

    lines = [
        "/* Generated by Tools/ConvertPetWalk.py. */",
        "#define PET_SPRITE_WIDTH       64",
        "#define PET_SPRITE_HEIGHT      64",
        "#define PET_WALK_FRAME_COUNT    3",
        "",
        "static const GUI_COLOR _PetWalkColors[256] = {",
    ]
    for offset in range(0, len(colors), 8):
        values = ", ".join(f"0x{value:08X}u" for value in colors[offset:offset + 8])
        lines.append(f"  {values},")
    lines += [
        "};",
        "",
        "static const GUI_LOGPALETTE _PetWalkPalette = {",
        "  256, 1, _PetWalkColors",
        "};",
        "",
        "static const unsigned char _PetWalkPixels[PET_WALK_FRAME_COUNT][PET_SPRITE_WIDTH * PET_SPRITE_HEIGHT] = {",
    ]
    for frame in frames_pixels:
        lines.append("  {")
        for offset in range(0, len(frame), 16):
            values = ", ".join(f"0x{value:02X}" for value in frame[offset:offset + 16])
            lines.append(f"    {values},")
        lines.append("  },")
    lines += [
        "};",
        "",
        "static const GUI_BITMAP _PetWalkBitmaps[PET_WALK_FRAME_COUNT] = {",
        "  { PET_SPRITE_WIDTH, PET_SPRITE_HEIGHT, PET_SPRITE_WIDTH, 8, _PetWalkPixels[0], &_PetWalkPalette, NULL },",
        "  { PET_SPRITE_WIDTH, PET_SPRITE_HEIGHT, PET_SPRITE_WIDTH, 8, _PetWalkPixels[1], &_PetWalkPalette, NULL },",
        "  { PET_SPRITE_WIDTH, PET_SPRITE_HEIGHT, PET_SPRITE_WIDTH, 8, _PetWalkPixels[2], &_PetWalkPalette, NULL },",
        "};",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="ascii")
    print(f"Wrote {PREVIEW}")
    print(f"Wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
